/*
  Builds src/app/shared/icon-data.ts: the shapes of the icons the app draws.

    node tools/icons.mjs        (or: npm run icons)

  The shapes come from the lucide-static package, which is a development dependency and is
  not part of the app. Only the icons named below are copied. The cricket bat is not in
  Lucide, so it is drawn here in the same style: a 24 by 24 grid and 2 unit round strokes.

  To add an icon: add its Lucide name to NAMES, run this, and use <app-icon name="..." />.
  Lucide's licence travels with the build as public/licenses/lucide.txt.
*/
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import * as prettier from "prettier";

const PROJECT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const LUCIDE = join(PROJECT, "node_modules", "lucide-static");
const OUT = join(PROJECT, "src", "app", "shared", "icon-data.ts");

const NAMES = [
  "activity", "arrow-left", "arrow-right", "bluetooth", "calendar-days", "chart-line", "check",
  "chevron-left", "chevron-right", "circle-check", "circle-x", "compass", "eye", "eye-off",
  "gauge", "house", "info", "lightbulb", "lock", "mail", "play", "radio", "square",
  "triangle-alert", "user", "users", "x",
];

/** Drawn for this app. The blade runs from bottom left, the handle points to the top right, and a ball sits beside it. */
const OWN = {
  bat: [
    ["path", { d: "M7 21 3 17l9-9 4 4Z" }],
    ["path", { d: "m14 10 6-6" }],
    ["circle", { cx: "18.5", cy: "18.5", r: "2.5" }],
  ],
};

const SHAPE_KEYS = { path: ["d"], circle: ["cx", "cy", "r"], rect: ["x", "y", "width", "height", "rx"] };

const lucide = JSON.parse(readFileSync(join(LUCIDE, "icon-nodes.json"), "utf8"));
const version = JSON.parse(readFileSync(join(LUCIDE, "package.json"), "utf8")).version;

const icons = {};
for (const name of NAMES) {
  if (!lucide[name]) throw new Error(`Lucide ${version} has no icon named "${name}"`);
  icons[name] = lucide[name];
}
Object.assign(icons, OWN);

const lines = Object.keys(icons).sort().map(name => {
  const shapes = icons[name].map(([tag, attrs]) => {
    const keys = SHAPE_KEYS[tag];
    if (!keys) throw new Error(`Icon "${name}" uses <${tag}>, which the Icon component cannot draw yet. Add it to SHAPE_KEYS here and to the template in src/app/shared/icon.ts.`);
    const extra = Object.keys(attrs).filter(k => !keys.includes(k) && !(tag === "rect" && k === "ry"));
    if (extra.length) throw new Error(`Icon "${name}": <${tag}> has attributes this tool does not copy: ${extra.join(", ")}`);
    const fields = keys.filter(k => attrs[k] !== undefined).map(k => `${k}: ${JSON.stringify(String(attrs[k]))}`);
    return `{ tag: ${JSON.stringify(tag)}, ${fields.join(", ")} }`;
  });
  return `  ${JSON.stringify(name)}: [\n${shapes.map(s => "    " + s + ",").join("\n")}\n  ],`;
});

const source = `// Generated by tools/icons.mjs. Do not edit by hand: change the list there and run it again.
// Shapes from Lucide ${version} (https://lucide.dev), ISC licence, see public/licenses/lucide.txt.
// "bat" was drawn for this app.

export type IconShape =
  | { tag: 'path'; d: string }
  | { tag: 'circle'; cx: string; cy: string; r: string }
  | { tag: 'rect'; x: string; y: string; width: string; height: string; rx?: string };

export const ICONS = {
${lines.join("\n")}
} satisfies Record<string, IconShape[]>;

export type IconName = keyof typeof ICONS;
`;
// Formatted like the rest of the TypeScript, so `prettier --check` stays quiet about it.
writeFileSync(OUT, await prettier.format(source, { ...(await prettier.resolveConfig(OUT)), filepath: OUT }));

mkdirSync(join(PROJECT, "public", "licenses"), { recursive: true });
copyFileSync(join(LUCIDE, "LICENSE"), join(PROJECT, "public", "licenses", "lucide.txt"));
console.log(`wrote ${Object.keys(icons).length} icons to ${OUT}`);
